def frontmatter(meta: dict) -> str:
    lines = ["---"]
    for k, v in meta.items():
        if isinstance(v, list):
            lines.append(f"{k}:")
            for item in v:
                lines.append(f"  - {item}")
        elif isinstance(v, bool):
            lines.append(f"{k}: {'true' if v else 'false'}")
        else:
            # YAML 安全引号
            s = str(v).replace('"', '\\"')
            lines.append(f'{k}: "{s}"')
    lines.append("---")
    lines.append("")
    return "\n".join(lines)


def wrap(doc_id: str, meta: dict, body: str) -> tuple[str, str]:
    """返回 (filename, full_markdown)。"""
    fn = meta["filename"]
    content = frontmatter({**meta, "doc_id": doc_id}) + body.strip() + "\n"
    return fn, content


